export const LANGS = Object.keys(DICT);
const STORAGE_KEY = 'rokehan-lang';
let current = 'en';

export function getLang() {
  return current;
}

const has = (code) => Object.prototype.hasOwnProperty.call(DICT, code);

// Map any language tag (ja-JP, zh-TW, en_US, ...) to a supported code, or null.
function resolve(tag) {
  if (!tag) return null;
  const c = String(tag).trim();
  if (has(c)) return c;
  const l = c.toLowerCase();
  if (l.startsWith('zh')) return /(-tw|-hk|-mo|hant)/.test(l) ? 'zh-Hant' : 'zh-Hans';
  const base = l.split(/[-_]/)[0];
  return has(base) ? base : null;
}

/** Translate a key with {name} interpolation. Falls back to English, then to the key itself. */
export function t(key, vars) {
  let s = DICT[current]?.[key];
  if (s === undefined) s = DICT.en[key];
  if (s === undefined) return key;
  if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (Object.prototype.hasOwnProperty.call(vars, k) ? String(vars[k]) : m));
  return s;
}

/** Set the active language, update <html lang>, the select and all static text. */
export function setLang(code) {
  current = resolve(code) || 'en';
  document.documentElement.lang = current;
  const sel = document.getElementById('langSelect');
  if (sel && sel.value !== current) sel.value = current;
  applyI18n();
  document.title = t('app.title');
  return current;
}

/** Apply data-i18n (textContent) and data-i18n-attr="attr:key;attr:key" (attributes) under root. */
export function applyI18n(root = document) {
  root.querySelectorAll('[data-i18n]').forEach((el) => {
    el.textContent = t(el.dataset.i18n);
  });
  root.querySelectorAll('[data-i18n-attr]').forEach((el) => {
    for (const pair of el.dataset.i18nAttr.split(';')) {
      const i = pair.indexOf(':');
      if (i < 0) continue;
      const attr = pair.slice(0, i).trim();
      const key = pair.slice(i + 1).trim();
      if (attr && key) el.setAttribute(attr, t(key));
    }
  });
}

/** Pick the initial language (saved choice, then browser languages, then English) and wire the select. */
export function initI18n() {
  let saved = null;
  try {
    saved = localStorage.getItem(STORAGE_KEY);
  } catch {
    saved = null;
  }
  let code = resolve(saved);
  if (!code) {
    const prefs = [...(navigator.languages || []), navigator.language].filter(Boolean);
    for (const p of prefs) {
      code = resolve(p);
      if (code) break;
    }
  }
  setLang(code || 'en');

  const sel = document.getElementById('langSelect');
  if (sel) {
    sel.value = current;
    sel.addEventListener('change', () => {
      const next = resolve(sel.value) || 'en';
      try {
        localStorage.setItem(STORAGE_KEY, next);
      } catch {
        /* storage unavailable: the choice just won't persist */
      }
      setLang(next);
      window.dispatchEvent(new CustomEvent('langchange', { detail: { lang: next } }));
    });
  }
  return current;
}
